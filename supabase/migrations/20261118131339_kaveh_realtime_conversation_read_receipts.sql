-- Publish conversation member cursor changes so clients can synchronize read receipts.
-- Realtime still applies the table's RLS policies for each subscriber.
do $migration$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'conversation_members'
  ) then
    alter publication supabase_realtime add table public.conversation_members;
  end if;
end;
$migration$;
