create table public.platform_appearance_versions (
  id uuid primary key default gen_random_uuid(),
  version bigint generated by default as identity unique,
  config jsonb not null default '{}'::jsonb check (jsonb_typeof(config) = 'object'),
  is_published boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create unique index platform_appearance_one_published
  on public.platform_appearance_versions (is_published)
  where is_published = true;

alter table public.platform_appearance_versions enable row level security;
revoke all on public.platform_appearance_versions from anon, authenticated;
grant select on public.platform_appearance_versions to anon, authenticated;
create policy "public can read published appearance"
  on public.platform_appearance_versions
  for select to anon, authenticated
  using (is_published = true);

create or replace function public.publish_platform_appearance(p_config jsonb, p_actor uuid)
returns table(id uuid, version bigint, config jsonb, created_at timestamptz)
language plpgsql
set search_path = ''
as $$
begin
  if jsonb_typeof(p_config) <> 'object' then
    raise exception 'config_must_be_object';
  end if;

  update public.platform_appearance_versions
    set is_published = false
    where is_published = true;

  return query
    insert into public.platform_appearance_versions (config, is_published, created_by)
    values (p_config, true, p_actor)
    returning platform_appearance_versions.id,
              platform_appearance_versions.version,
              platform_appearance_versions.config,
              platform_appearance_versions.created_at;
end;
$$;

revoke all on function public.publish_platform_appearance(jsonb, uuid) from public, anon, authenticated;
grant execute on function public.publish_platform_appearance(jsonb, uuid) to service_role;

